// Prints supabase/seed.sql from the defaults in lib/content.ts:
//   node --experimental-strip-types scripts/seed.ts > supabase/seed.sql
import { content, profile, settings } from "../lib/content.ts";

const rows = { en: content.en, vi: content.vi, profile, settings };
const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
console.log("-- Generated by scripts/seed.ts. Overwrites the 4 rows with the defaults from lib/content.ts.");
for (const [key, data] of Object.entries(rows)) {
  console.log(
    `insert into public.site_content (key, data) values (${q(key)}, ${q(JSON.stringify(data))}::jsonb)\n  on conflict (key) do update set data = excluded.data;`,
  );
}
